// Human review of generated statements. This is the only code that changes a
// statement's reviewStatus; the AI workflow only ever inserts PENDING rows (also
// enforced by database triggers). Reviewing never changes Release.status.

import { recordEvent } from "@/lib/app-log";
import { getDb } from "@/lib/db";
import { nextReviewStatus, type ReviewRequest } from "@/lib/domain/review";
import { ApiError } from "@/lib/errors";
import { assessStaleness, toStatementDto, toVersionSnapshot, type StatementDto } from "@/lib/services/analysis";
import type { ServiceContext } from "@/lib/services/releases";

export async function reviewStatement(
  statementId: string,
  request: ReviewRequest,
  ctx: ServiceContext,
): Promise<{ statement: StatementDto; releaseId: string; versionNumber: number }> {
  const db = getDb();
  const statement = await db.generatedStatement.findUnique({
    where: { id: statementId },
    include: {
      run: { select: { status: true } },
      version: { select: { id: true, versionNumber: true, releaseId: true } },
    },
  });
  if (!statement) throw new ApiError(404, "NOT_FOUND", "Statement not found");

  // Only statements of the current analysis of a version can be reviewed:
  // the run must have succeeded and must be the latest successful run.
  const latestRun = await db.analysisRun.findFirst({
    where: { versionId: statement.versionId, status: "SUCCEEDED" },
    orderBy: { createdAt: "desc" },
    select: { id: true },
  });
  if (statement.run.status !== "SUCCEEDED" || latestRun?.id !== statement.runId) {
    throw new ApiError(
      409,
      "CONFLICT",
      "This statement belongs to a superseded analysis run. Review the statements of the latest run instead.",
    );
  }

  const transition = nextReviewStatus(statement.reviewStatus, request.action);
  if (!transition.ok) throw new ApiError(409, "CONFLICT", transition.reason);

  // A statement that is stale relative to the current version cites evidence that no
  // longer matches the release. It can be rejected, but not approved or edited: it has
  // to be regenerated by re-running analysis.
  if (request.action !== "reject") {
    const current = await db.releaseVersion.findFirst({
      where: { releaseId: statement.version.releaseId },
      orderBy: { versionNumber: "desc" },
    });
    if (current && current.id !== statement.versionId) {
      const own = await db.releaseVersion.findUniqueOrThrow({ where: { id: statement.versionId } });
      const [assessed] = assessStaleness([toStatementDto(statement)], toVersionSnapshot(own), toVersionSnapshot(current));
      if (assessed.stale.stale) {
        throw new ApiError(
          409,
          "CONFLICT",
          `This statement is stale relative to v${current.versionNumber} (${assessed.stale.reasons.join("; ")}). Re-run analysis to regenerate it; a stale statement can only be rejected.`,
          { stale: assessed.stale },
        );
      }
    }
  }

  const effective = statement.editedContent ?? statement.aiContent;
  if (request.action === "edit" && request.content === effective) {
    throw new ApiError(422, "NO_CHANGES", "The edited content is identical to the current content.");
  }

  const reviewedAt = new Date();
  const data = {
    reviewStatus: transition.status,
    reviewedBy: request.reviewer,
    reviewedAt,
    // Only a rejection carries a note; aiContent is never touched (and is immutable in the database).
    reviewNote: request.action === "reject" ? (request.note || null) : null,
    ...(request.action === "edit" ? { editedContent: request.content } : {}),
  };

  // Compare-and-set on the status read above, so concurrent reviews can't silently overwrite each other.
  const { count } = await db.generatedStatement.updateMany({
    where: { id: statementId, reviewStatus: statement.reviewStatus },
    data,
  });
  if (count === 0) {
    throw new ApiError(409, "CONFLICT", "The statement was reviewed by someone else in the meantime. Reload and try again.");
  }

  const updated = await db.generatedStatement.findUniqueOrThrow({ where: { id: statementId } });
  const { releaseId, versionNumber } = statement.version;

  await recordEvent(ctx.log, {
    level: "info",
    event: "statement.reviewed",
    requestId: ctx.requestId,
    releaseId,
    context: {
      statementId,
      versionId: statement.versionId,
      versionNumber,
      runId: statement.runId,
      kind: statement.kind,
      action: request.action,
      reviewer: request.reviewer,
      fromStatus: statement.reviewStatus,
      toStatus: transition.status,
      timestamp: reviewedAt.toISOString(),
      ...(request.action === "edit" ? { editedLength: request.content.length } : {}),
      ...(request.action === "reject" ? { hasNote: Boolean(request.note) } : {}),
    },
  });

  return { statement: toStatementDto(updated), releaseId, versionNumber };
}
